        hard  : 정의나 핵심 특징을 교과서적 존댓말 평서문으로 간결하게 서술하세요.
    """.trimIndent()

    fun guideFor(category: String): String =
        CATEGORY_GUIDE[QuizCategory.normalize(category)] ?: DEFAULT_GUIDE

    /**
     * 1음절 단어에만 붙는 블록.
     *
     * ── 여기서 한 가지 타협을 했습니다 ────────────────────────
     * "모델에게 음절 수를 알려주지 않는다" 는 v3의 원칙과 이 블록은 사실 충돌합니다.
     * "초성 힌트를 줄 수 없다" 는 말은 눈치 빠른 모델에게 1음절이라는 신호가 됩니다.
     *
     * 그럼에도 넣는 이유는, 모델은 이미 정답 단어를 통째로 보고 있어서
     * 음절 수를 **원래부터 알고 있기** 때문입니다. 원칙의 진짜 목적은
     * "모델이 힌트에 글자 수를 쓰지 못하게" 하는 것이고, 그건 프롬프트가 아니라
     * [HintValidator] 의 금지 표현("글자", "음절")이 기계적으로 막습니다.
     * 그래서 개수를 직접 말하지 않는 선에서만 상황을 설명합니다.
     */
    private val SINGLE_SYLLABLE_BLOCK: String = """
        [이 단어에는 특별 규칙이 적용됩니다]
        - 이 단어는 부분 공개 힌트를 줄 수 없습니다. 화면에 나가는 것은 당신이 만든 문장 중 단 하나뿐입니다.
        - 그러므로 난이도 사다리를 만들지 마세요. easy / normal / hard 를 각각
          '그것 하나만 보고도 정답을 떠올릴 수 있는 힌트' 로 쓰되, 서로 다른 각도에서 접근하세요.
          예) easy → 밈·말장난·감탄사로 인상, normal → 의인화·의성어로 특징 묘사,
              hard → 교과서적 정의 한 문장. 축을 달리하면 대체 가능성이 생깁니다.
        - 금지 문자열 목록이 매우 짧습니다. 짧을수록 조사나 합성어, 관용구 속에
          자기도 모르게 섞여 들어갑니다. 문장을 다 쓴 뒤 그 문자열이 어디에도 없는지
          반드시 다시 확인하세요. 흔히 놓치는 곳은 '~라는 OO입니다' 같은 문장 끝입니다.
    """.trimIndent()

    /**
     * 사용자 메시지를 만듭니다.
     *
     * @param candidatesPerLevel 난이도마다 요청할 후보 개수.
     * @param feedback 직전 시도가 검증에서 떨어진 사유. 첫 시도면 null.
     *                 같은 실수를 반복하지 않게 하는 장치입니다.
     */
    fun buildUserMessage(
        entry: WordEntry,
        candidatesPerLevel: Int = DEFAULT_CANDIDATES_PER_LEVEL,
        feedback: String? = null
    ): String {
        // 주의: 여기서 raw string + trimIndent() 를 쓰면 안 됩니다.
        // trimIndent() 는 보간이 끝난 뒤의 문자열에 적용되므로,
        // 줄바꿈이 들어 있는 값을 끼워 넣는 순간 공통 들여쓰기가 0으로 계산되어
        // 프롬프트 전체의 들여쓰기가 그대로 남아 버립니다.
        // 줄 단위로 직접 조립하는 편이 안전하고 결과도 눈으로 확인하기 쉽습니다.
        val n = candidatesPerLevel.coerceIn(CANDIDATE_RANGE)
        val banned = Hangul.leakFragments(entry.word).joinToString(", ") { "\"" + it + "\"" }

        return buildString {
            appendLine("카테고리: " + entry.quizCategoryName)
            appendLine("정답 단어: " + entry.word)
            if (entry.definition.isNotBlank()) {
                appendLine("사전 뜻풀이: " + entry.definition.replace("\n", " ").trim())
            }
            appendLine()
            appendLine("카테고리별 지침: " + guideFor(entry.quizCategoryName))
            appendLine()
            appendLine("금지 문자열(이 중 어떤 것도 힌트에 등장하면 안 됩니다): $banned")

            if (entry.isSingleSyllable) {
                appendLine()
                appendLine(SINGLE_SYLLABLE_BLOCK)
            }

            appendLine()
            append("위 정답 단어에 대한 힌트를 easy / normal / hard 각 난이도마다 ${n}개씩 만드세요.")

            if (!feedback.isNullOrBlank()) {
                appendLine()
                appendLine()
                appendLine("[직전 시도가 거부되었습니다]")
                appendLine("사유: " + feedback.replace("\n", " ").trim())
                append("같은 실수를 반복하지 마세요. 문제가 된 표현을 완전히 다른 말로 바꿔 다시 쓰세요.")
            }
        }
    }
}
