          권장 길이: 공백 포함 2~15자. 정보는 최소한으로, 분위기와 인상만 던지세요.

          ▶ 핵심 방향: 뻔한 설명 금지. 밈·말장난·의인화·감탄사로 능청스럽게 접근하세요.
          - 명사형 또는 감탄사형으로 짧게 치고 빠지는 힌트를 권장합니다.
          - !, ?, ~, ㅋㅋ, ㅎㅎ 같은 구어체 표현을 적극 사용하세요.
          - 반말과 존댓말을 자유롭게 혼용해도 됩니다.
          - 의성어·의태어·농담·말장난을 활용하면 좋습니다.
          예) 망고스틴(과일) → "과일의 여왕ㅋㅋ"
          예) 삼겹살(음식)  → "치이이이익 (고기를 표현한 의성어)" or "불판에 춤을 춰요"(고기가 구워지는 모습을 의인화) 
          or "김치 공주 보고 싶소(삼겹살과 궁합이 좋은 김치를 삼겹살을 의인화하여 유쾌하게 표현)"  
          
      
          예) 사자(동물)    → "나는 돈이 많아!"  ← '사자(買)'를 이용한 말장난
          예) 일취월장(사자성어) → "이야~ 너 정말!"  ← 해당 사자성어가 뒤따를 법한 예문

        - normal(중): 중간 힌트. easy보다 정보량이 많아야 하고, 후보가 두세 개로 줄어드는 수준입니다.
          권장 길이: 공백 포함 2~15자.

          ▶ 핵심 방향: easy처럼 유머러스하되, 단어의 눈에 보이는 특징·색·크기·쓰임새·시기를
