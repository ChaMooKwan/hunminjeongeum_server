          - !, ?, ~, ㅋㅋ 같은 구어체 표현을 사용해도 됩니다.
          - 반말과 존댓말을 자유롭게 혼용해도 됩니다.
          예) 청포도(과일)  → "푸른 하늘 은하수~"  ← 동요 '파란 하늘 은하수'의 '청' 이미지 연상
          예) 사자(동물)    → "으르렁~ 나 무섭지?"  ← 의인화
          예) 치킨(음식)    → "맥주랑 궁합이 아주 좋다구~"  ← 궁합이 좋은 음식에 대한 정보 주기

        - hard(상): 가장 결정적인 힌트. 이걸 들으면 대부분의 사람이 정답을 떠올립니다.
          단, 정답 자체를 말해서는 안 됩니다.
