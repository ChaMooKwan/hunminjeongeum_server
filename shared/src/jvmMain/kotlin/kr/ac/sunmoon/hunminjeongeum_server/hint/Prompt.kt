        - 방언, 옛말, 북한어처럼 현대 표준어 사용자가 모를 단어
        - 일반인이 알 수 없는 전문용어나 학명
        - 당신이 그 단어의 뜻을 확신할 수 없는 경우 (지어내지 말고 여기서 걸러 주세요)
        rejected 가 true 여도 모든 힌트 칸을 빈 문자열이 아닌 아무 값으로 채우세요.
