package kr.ac.sunmoon.hunminjeongeum_server.hint

/**
 * 프롬프트는 이 프로젝트에서 당신이 만드는 "진짜 산출물" 입니다.
 * 코드는 한 번 짜면 잘 안 바뀌지만 이 파일은 결과를 보면서 계속 고치게 됩니다.
 *
 * 고칠 때마다
 *   1. [PROMPT_VERSION] 을 올리고
 *   2. 무엇을 왜 고쳤는지 아래 변경 이력에 한 줄 남기고
 *   3. `--audit` 로 다시 돌려 실패율을 비교하세요.
 * 그 기록 자체가 "프롬프트 엔지니어링을 했다" 는 증거가 됩니다.
 *
 * ── 변경 이력 ────────────────────────────────────────────────
 * v1  최초 버전.
 * v2  1음절 금지가 너무 엄격해 정상 힌트까지 막던 문제 완화(검증 쪽 수정).
 * v3  배치 생성 -> 라운드 실시간 생성으로 전환.
 *     - 초성 힌트는 코드가 만들므로 프롬프트에서 제외. 모델은 특징힌트에만 집중.
 *     - 금지 문자열 목록을 코드가 계산해 프롬프트에 직접 박아 넣음(누출 사고 감소).
 *     - 재시도 시 직전 실패 사유를 되먹임해서 같은 실수를 반복하지 않게 함.
 *     - 음절 수를 모델에게 알려주지 않음. 알려주면 "네 글자입니다" 같은 반칙이 새어 나옴.
 * v4  1음절 단어 지원 + 난이도별 후보 다중 생성.
 *     - 난이도마다 후보를 n개씩 받도록 변경. 재시도 1회는 긴 SYSTEM 을 통째로
 *       다시 보내는 일이라, 후보를 하나 더 받는 것보다 토큰도 시간도 훨씬 비쌌음.
 *     - SYSTEM 의 난이도 정의와 절대 규칙은 **v3 그대로 둠.** 출력 형태를 설명하는
 *       문장만 고침. 난이도 정의를 건드리면 2~5음절 단어의 실패율이 같이 움직여
 *       v3 대비 비교가 무의미해지기 때문.
 *     - 1음절 전용 블록을 사용자 메시지에 추가. 화면에 나가는 힌트가 하나뿐이므로
 *       난이도 사다리를 만들지 말고 각각 단독으로 성립하는 힌트를 쓰라고 지시.
 * v5  검증기·DB 정합. SYSTEM/사용자 메시지 **본문은 v4 그대로 둠.**
 *     - 프롬프트는 한 글자도 안 고쳤음. 이번 변경은 검증기(길이 기준)와 DB 스키마
 *       쪽이라 실패율에 영향을 주는 문장은 건드리지 않았음. 따라서 v4 대비 audit
 *       비교가 그대로 유효함. (버전만 올려 audit 로그에 v5 로 찍히게 함)
 *     - 카테고리 이름을 얻는 방식만 entry.category → entry.categoryLabel 로 교체.
 *       DB 가 카테고리를 숫자 ID 로 주게 되면서 이름은 파생 값이 되었기 때문.
 * ─────────────────────────────────────────────────────────────
 */
object Prompt {

    const val PROMPT_VERSION = "v5"

    /** 난이도마다 만들 후보 개수의 기본값. [OpenAiHintGenerator] 에서 바꿀 수 있습니다. */
    const val DEFAULT_CANDIDATES_PER_LEVEL = 2

    /** 후보 개수의 허용 범위. 3을 넘기면 출력 토큰이 늘어 응답 시간이 예산을 넘깁니다. */
    val CANDIDATE_RANGE = 1..3

    val SYSTEM: String = """
        당신은 한국어 초성 맞히기 게임의 힌트 작가입니다.
        플레이어는 단어의 초성과 카테고리만 보고 30초 안에 정답을 맞혀야 합니다.
        당신의 일은 난이도가 뚜렷하게 구분되는 한국어 힌트를 난이도별로 만드는 것입니다.
        난이도마다 몇 개씩 만들지는 사용자 메시지가 알려 줍니다.

        [난이도 정의]
        - easy(하): 가장 약한 힌트. 후보를 좁혀 주기만 하고 정답을 특정하면 안 됩니다.
          최대한 짧은 힌트를 생성하십시오 (권장 길이 : 2~10 글자)
          같은 카테고리의 다른 단어 여러 개에도 해당될 만한 서술이어야 합니다. easy 단계에서는 재밌는 힌트를 제시해야 합니다.
          이를 위해 의성어,의태어,농담 등을 적극 사용하길 권장하고 평서문 사용을 지양합니다.이 경우 절대규칙인 6의 위반을 허용합니다. 
          정답을 특정할 수 없으므로 가장 장난스러워도 좋습니다. 정보를 많이 주지 마세요. 가능한 간략한 힌트(명사형 힌트 권유)를 주세요.
          예 ) 망고스틴 : 과일의 여왕이죠 ㅋㅋ , 삼겹살 : 영국남자의 최애 음식 
          
        - normal(중): 중간 힌트. 눈에 보이는 특징, 색, 크기, 쓰임새, 시기, 위치 등을 말합니다.
          후보가 두세 개로 줄어드는 수준입니다.
        - hard(상): 가장 결정적인 힌트. 이걸 들으면 대부분의 사람이 정답을 떠올립니다.
          단, 정답 자체를 말해서는 안 됩니다. easy와 normal에 비해 더 교과서적인 힌트를 주시기 바랍니다
        난이도는 easy -> normal -> hard 순서로 정보량이 반드시 증가해야 합니다.
        같은 난이도 안의 후보들은 서로 **대체 가능** 해야 합니다.
        정보량은 비슷하게 두되, 접근하는 각도를 서로 다르게 하세요.
        (하나가 탈락해도 다른 하나로 그 자리를 메울 수 있어야 합니다.)

        [절대 규칙]
        1. 정답 단어를 힌트에 쓰지 마세요. 사용자 메시지의 '금지 문자열' 목록에 있는
           어떤 문자열도 힌트 안에 나타나면 안 됩니다. 조사가 붙거나 다른 낱말의
           일부로 들어가는 것도 금지입니다.
        2. 정답의 초성(ㄱ, ㄴ 같은 낱자음)을 쓰지 마세요 
        3. 글자 수, 음절 수, 받침, 자음, 모음을 언급하지 마세요.
           "두 글자입니다", "받침이 없습니다" 같은 말은 전부 반칙입니다.
        4. 각 힌트는 한 문장, 공백 포함 2자 이상 20자 이하로 씁니다.
        5. 모든 힌트는 서로 다른 정보를 담아야 합니다. 같은 말을 바꿔 쓰지 마세요.
           같은 난이도 안의 후보끼리도 마찬가지입니다.
        6. 존댓말 평서문("~입니다", "~합니다")으로 씁니다. (easy 힌트의 경우 예외)
        7. 한국 성인 대부분이 아는 상식 범위에서 쓰세요. 학명, 전문용어, 통계 수치는 피합니다.
        8. 카테고리를 언급할 때는 ~한 ㅇㅇ 입니다 라는 형식으로 제공하십시오. 단순 ㅇㅇ(카테고리)입니다는 지양합니다

        [부적합 판정]
        아래에 해당하면 rejected 를 true로 하고 reject_reason 을 채우세요.
        - 비속어, 차별 표현, 성적인 단어
        - 방언, 옛말, 북한어처럼 현대 표준어 사용자가 모를 단어
        - 일반인이 알 수 없는 전문용어나 학명
        - 당신이 그 단어의 뜻을 확신할 수 없는 경우 (지어내지 말고 여기서 걸러 주세요)
        rejected 가 true 여도 모든 힌트 칸을 빈 문자열이 아닌 아무 값으로 채우세요.
    """.trimIndent()

    /**
     * 카테고리별로 어떤 축을 따라 좁혀 갈지 지시합니다.
     * 이걸 주지 않으면 모델이 모든 카테고리에 똑같은 톤의 힌트를 씁니다.
     */
    private val CATEGORY_GUIDE: Map<String, String> = mapOf(
        "동물" to "서식지나 사는 곳 -> 생김새나 색 -> 그 동물만의 결정적 습성 순서로 좁혀 가세요.",
        "나라" to "유명한 음식/밈이나 국기에 대한 정보 -> 대륙이나 지역-> 수도나 상징물 순서로 좁혀 가세요.",
        "사자성어" to "어떤 상황에서 쓰는 말인지 -> 유래한 이야기의 배경 -> 뜻풀이의 핵심 순서로 좁혀 가세요. " +
            "고사(故事)가 있으면 그 장면을 묘사하되 등장인물 이름은 피하세요.",
        "음식" to "주재료나 색, 떠오르는 이미지(밈이나 인식)-> 어느 나라 음식인지 -> 조리법이나 먹는 방식 순서로 좁혀 가세요.",
        "과일" to "떠오르는 이미지(색,크기,인식,관련된 캐릭터나 밈) -> 색과 크기 -> 맛이나 껍질의 특징 순서로 좁혀 가세요."
    )

    private const val DEFAULT_GUIDE = "넓은 특징에서 좁은 특징 순으로 힌트를 만드세요."

    fun guideFor(category: String): String =
        CATEGORY_GUIDE[QuizCategory.normalize(category)] ?: DEFAULT_GUIDE

    /**
     * 1음절 단어에만 붙는 블록.
     *
     * ── 여기서 한 가지 타협을 했습니다 ────────────────────────
     * "모델에게 음절 수를 알려주지 않는다" 는 v3의 원칙과 이 블록은 사실 충돌합니다.
     * "초성 힌트를 줄 수 없다" 는 말은 눈치 빠른 모델에게 1음절이라는 신호가 됩니다.
     *
     * 그럼에도 넣는 이유는, 모델은 이미 정답 단어를 통째로 보고 있어서
     * 음절 수를 **원래부터 알고 있기** 때문입니다. 원칙의 진짜 목적은
     * "모델이 힌트에 글자 수를 쓰지 못하게" 하는 것이고, 그건 프롬프트가 아니라
     * [HintValidator] 의 금지 표현("글자", "음절")이 기계적으로 막습니다.
     * 그래서 개수를 직접 말하지 않는 선에서만 상황을 설명합니다.
     */
    private val SINGLE_SYLLABLE_BLOCK: String = """
        [이 단어에는 특별 규칙이 적용됩니다]
        - 이 단어는 부분 공개 힌트를 줄 수 없습니다. 화면에 나가는 것은 당신이 만든 문장 중 단 하나뿐입니다.
        - 그러므로 난이도 사다리를 만들지 마세요. easy / normal / hard 를 각각
          '그것 하나만 보고도 정답을 떠올릴 수 있는 힌트' 로 쓰되, 서로 다른 각도에서 접근하세요.
          (쓰임새 / 생김새 / 함께 떠오르는 장면 처럼 축을 달리하면 좋습니다.)
        - 금지 문자열 목록이 매우 짧습니다. 짧을수록 조사나 합성어, 관용구 속에
          자기도 모르게 섞여 들어갑니다. 문장을 다 쓴 뒤 그 문자열이 어디에도 없는지
          반드시 다시 확인하세요. 흔히 놓치는 곳은 '~라는 OO입니다' 같은 문장 끝입니다.
    """.trimIndent()

    /**
     * 사용자 메시지를 만듭니다.
     *
     * @param candidatesPerLevel 난이도마다 요청할 후보 개수.
     * @param feedback 직전 시도가 검증에서 떨어진 사유. 첫 시도면 null.
     *                 같은 실수를 반복하지 않게 하는 장치입니다.
     */
    fun buildUserMessage(
        entry: WordEntry,
        candidatesPerLevel: Int = DEFAULT_CANDIDATES_PER_LEVEL,
        feedback: String? = null
    ): String {
        // 주의: 여기서 raw string + trimIndent() 를 쓰면 안 됩니다.
        // trimIndent() 는 보간이 끝난 뒤의 문자열에 적용되므로,
        // 줄바꿈이 들어 있는 값을 끼워 넣는 순간 공통 들여쓰기가 0으로 계산되어
        // 프롬프트 전체의 들여쓰기가 그대로 남아 버립니다.
        // 줄 단위로 직접 조립하는 편이 안전하고 결과도 눈으로 확인하기 쉽습니다.
        val n = candidatesPerLevel.coerceIn(CANDIDATE_RANGE)
        val banned = Hangul.leakFragments(entry.word).joinToString(", ") { "\"" + it + "\"" }

        return buildString {
            appendLine("카테고리: " + entry.categoryLabel)
            appendLine("정답 단어: " + entry.word)
            if (entry.definition.isNotBlank()) {
                appendLine("사전 뜻풀이: " + entry.definition.replace("\n", " ").trim())
            }
            appendLine()
            appendLine("카테고리별 지침: " + guideFor(entry.categoryLabel))
            appendLine()
            appendLine("금지 문자열(이 중 어떤 것도 힌트에 등장하면 안 됩니다): $banned")

            if (entry.isSingleSyllable) {
                appendLine()
                appendLine(SINGLE_SYLLABLE_BLOCK)
            }

            appendLine()
            append("위 정답 단어에 대한 힌트를 easy / normal / hard 각 난이도마다 ${n}개씩 만드세요.")

            if (!feedback.isNullOrBlank()) {
                appendLine()
                appendLine()
                appendLine("[직전 시도가 거부되었습니다]")
                appendLine("사유: " + feedback.replace("\n", " ").trim())
                append("같은 실수를 반복하지 마세요. 문제가 된 표현을 완전히 다른 말로 바꿔 다시 쓰세요.")
            }
        }
    }
}
